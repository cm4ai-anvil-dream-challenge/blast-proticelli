#!/usr/bin/env python3
"""Generate submission_test.wdl from submission.wdl, for a test run on AnVIL.

The submission contract forbids resources in the submitted WDL: the organizers
run a generated copy that adds them, along with their own workflow around the
Predict task. Imported tasks cannot be given resources by a calling workflow,
so a plain wrapper around submission.wdl would run with Cromwell's defaults
(no GPU, little memory). This script builds the test the same way the
organizers do: submission.wdl copied unchanged, the contract's reference
resources added to its runtime block, and a workflow block that calls Predict.

The command, image digest, struct, inputs and outputs are all copied, never
retyped, so the test runs exactly what is submitted.

Usage (from the repository folder):
    python scripts/make_submission_test.py           # write submission_test.wdl
    python scripts/make_submission_test.py --check   # fail if it is out of date

Reference resources: anvil-dream-participant docs/contract.md, "The reference
policy sets 8 CPUs, 32 GB of memory, a 75 GB SSD, one NVIDIA L4, zero
preemptible attempts by default, zero task retries, noAddress: false, and
predefinedMachineType: g2-standard-8". The organizers also set a time limit,
which this test does not.
"""

import argparse
import re
import sys
from pathlib import Path

SOURCE = Path("submission.wdl")
TARGET = Path("submission_test.wdl")

RESOURCES = [
    'cpu: 8',
    'memory: "32 GB"',
    'disks: "local-disk 75 SSD"',
    'gpuCount: 1',
    'gpuType: "nvidia-l4"',
    'predefinedMachineType: "g2-standard-8"',
    'preemptible: 0',
    'maxRetries: 0',
    'noAddress: false',
]

HEADER = """\
# GENERATED by scripts/make_submission_test.py from submission.wdl. Do not edit;
# change submission.wdl and run the script again.
#
# AnVIL test of the challenge submission. Identical to submission.wdl except:
#   - the contract's reference resources are added to the runtime block, as
#     the organizers add them to their copy (8 CPU, 32 GB, 75 GB SSD, 1 L4);
#   - a workflow block calls Predict, since Cromwell runs workflows.
# This file is not submitted.

"""

WORKFLOW = """
workflow submission_test {
  input {
    Array[PredictionInput] inputs
    File weights
  }

  call Predict {
    input:
      inputs = inputs,
      weights = weights
  }

  output {
    Array[File] predictions = Predict.predictions
  }
}
"""

# The runtime block of submission.wdl: exactly one docker line, nothing else.
RUNTIME = re.compile(r"^(?P<indent>[ \t]*)runtime \{\n(?P<docker>[ \t]*docker: \"[^\"]+\"\n)(?P=indent)\}$", re.M)


def generate(source_text):
    if not source_text.startswith("version 1.0\n"):
        sys.exit(f"ERROR: {SOURCE} must start with 'version 1.0'")
    if "\nworkflow " in source_text:
        sys.exit(f"ERROR: {SOURCE} has a workflow block; the contract allows none")
    matches = list(RUNTIME.finditer(source_text))
    if len(matches) != 1:
        sys.exit(f"ERROR: expected one runtime block in {SOURCE} holding only a docker line; found {len(matches)}")
    m = matches[0]
    inner = m.group("indent") + "  "
    runtime = (m.group("indent") + "runtime {\n" + m.group("docker")
               + "".join(f"{inner}{line}\n" for line in RESOURCES) + m.group("indent") + "}")
    body = source_text[:m.start()] + runtime + source_text[m.end():]
    body = body[len("version 1.0\n"):].lstrip("\n")
    return "version 1.0\n\n" + HEADER + body.rstrip("\n") + "\n" + WORKFLOW


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="Exit 1 if submission_test.wdl is out of date")
    args = ap.parse_args()

    expected = generate(SOURCE.read_text())
    if args.check:
        if not TARGET.is_file() or TARGET.read_text() != expected:
            sys.exit(f"{TARGET} is out of date; run: python scripts/make_submission_test.py")
        print(f"{TARGET} matches {SOURCE}")
        return
    TARGET.write_text(expected)
    print(f"Wrote {TARGET} from {SOURCE}")


if __name__ == "__main__":
    main()
